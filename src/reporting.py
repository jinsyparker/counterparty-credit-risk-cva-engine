"""Final results summary and README results block, generated from ``reports/tables``.

Nothing here computes a model quantity: it only reads the CSVs written by
``run_all.py`` and formats them, so every number in the written documents can be
traced to a generated table.
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

RESULTS_START, RESULTS_END = "<!-- results:start -->", "<!-- results:end -->"

PLAIN_DRIVER_NAMES = {
    "maturity_scale": "portfolio tenor", "spread_scale": "credit spread", "sigma": "rate volatility",
    "recovery_hazard_fixed": "recovery", "notional_scale": "notional", "mean_reversion": "mean reversion",
}


VALUE_FORMATS = {
    "maturity_scale": "×{:g}", "spread_scale": "×{:g}", "notional_scale": "×{:g}",
    "recovery_hazard_fixed": "{:.0%} (hazard fixed)", "sigma": "σ = {:.2%}", "mean_reversion": "a = {:.0%}",
}


def _k(x: float) -> str:
    return f"${x / 1e3:,.1f}k"


def _m(x: float) -> str:
    return f"${x / 1e6:,.2f}m"


def load_results(tables_dir: Path) -> dict[str, pd.DataFrame]:
    names = ["cva_summary", "exposure_summary", "cva_mitigation", "collateral_summary", "collateral_mpor_sensitivity", "convergence",
             "market_sensitivity", "sensitivity_tornado", "martingale_check"]
    return {name: pd.read_csv(tables_dir / f"{name}.csv") for name in names}


def headline_facts(r: dict[str, pd.DataFrame]) -> dict:
    cva = r["cva_summary"].set_index("netting_set_id")
    mit = r["cva_mitigation"]
    zero = mit[mit["stage"].str.contains("Zero threshold")].set_index("netting_set_id")["cva"]
    tornado = r["sensitivity_tornado"]
    spans = tornado.groupby("parameter")["change_vs_base"].agg(lambda v: v.max() - v.min()).sort_values(ascending=False)
    conv = r["convergence"]
    conv_total = conv[conv["netting_set_id"] == "TOTAL"].sort_values("n_paths")
    return {
        "cva_total": cva.loc["TOTAL", "cva_netted"], "cva_total_se": cva.loc["TOTAL", "cva_netted_se"],
        "cva": cva, "zero_csa_total": zero.sum(),
        "csa_further_reduction": 1.0 - zero.sum() / cva.loc["TOTAL", "cva_netted"],
        "drivers": [PLAIN_DRIVER_NAMES[p] for p in spans.index if p != "notional_scale"],
        "spans": spans, "conv_total": conv_total,
        "mpor_days": int(r["collateral_summary"]["mpor_days"].dropna().iloc[0]),  # base CSA scenarios share one MPoR
    }


def resume_bullets(r: dict[str, pd.DataFrame], n_paths: int, n_dates: int) -> list[str]:
    f = headline_facts(r)
    cva = f["cva"]
    drivers = ", ".join(f["drivers"][:4])
    return [
        f"Built a Monte Carlo counterparty-credit-risk engine in Python for a 10-swap USD interest-rate portfolio: bootstrapped "
        f"a US Treasury zero curve, simulated an exact one-factor Hull-White model ({n_paths:,} paths × {n_dates} dates, "
        f"martingale-tested) and priced unilateral CVA with pathwise discounting to ±{f['cva_total_se'] / f['cva_total']:.1%} "
        f"Monte Carlo precision.",
        f"Quantified counterparty-risk mitigation: legal netting cut portfolio CVA by {cva.loc['TOTAL', 'netting_reduction']:.0%} "
        f"({cva.loc['NS_A', 'netting_reduction']:.0%} for a balanced netting set vs {cva.loc['NS_B', 'netting_reduction']:.0%} "
        f"for a one-directional one), a zero-threshold CSA with a {f['mpor_days']}-day margin period removed a further "
        f"{f['csa_further_reduction']:.0%}, and common-random-number sensitivities ranked the CVA drivers ({drivers}).",
    ]


def _reduction(x: float) -> str:
    return "—" if abs(x) < 0.005 else f"−{x:.0%}"


def results_markdown(r: dict[str, pd.DataFrame], n_paths: int, n_dates: int, valuation_date: str,
                     include_note: bool = True, include_bullets: bool = True) -> str:
    """Compact results block for the README."""
    f = headline_facts(r)
    cva, exp = f["cva"], r["exposure_summary"].set_index("netting_set_id")
    mit = r["cva_mitigation"]
    note = [f"*Generated by `run_all.py` (valuation date {valuation_date}, {n_paths:,} paths, seed 42). "
            "Numbers come from `reports/tables`.*", ""] if include_note else []
    lines = note + [
        "| Netting set | EPE (time-avg EE) | Peak PFE 95% | CVA netted (± 1 s.e.) | CVA gross | Netting | Zero-threshold CSA |",
        "|---|---|---|---|---|---|---|",
    ]
    for ns in [n for n in cva.index if n != "TOTAL"]:
        zero = mit[(mit["netting_set_id"] == ns) & mit["stage"].str.contains("Zero threshold")]["cva"].iloc[0]
        lines.append(f"| {ns} | {_m(exp.loc[ns, 'epe_netted'])} | {_m(exp.loc[ns, 'peak_pfe95_netted'])} | "
                     f"{_k(cva.loc[ns, 'cva_netted'])} ± {_k(cva.loc[ns, 'cva_netted_se'])} | {_k(cva.loc[ns, 'cva_gross'])} | "
                     f"−{cva.loc[ns, 'netting_reduction']:.0%} | {_k(zero)} |")
    lines.append(f"| **Portfolio** | | | **{_k(f['cva_total'])} ± {_k(f['cva_total_se'])}** | {_k(cva.loc['TOTAL', 'cva_gross'])} | "
                 f"−{cva.loc['TOTAL', 'netting_reduction']:.0%} | {_k(f['zero_csa_total'])} |")
    if include_bullets:
        lines += ["", "**Project summary**", ""] + [f"- {b}" for b in resume_bullets(r, n_paths, n_dates)]
    return "\n".join(lines)


def final_summary_markdown(r: dict[str, pd.DataFrame], n_paths: int, n_dates: int, valuation_date: str) -> str:
    """The full results summary written to reports/final_project_summary.md."""
    f = headline_facts(r)
    cva = f["cva"]
    mit, mpor, tornado, mart = r["cva_mitigation"], r["collateral_mpor_sensitivity"], r["sensitivity_tornado"], r["martingale_check"]
    out = [
        "# Counterparty Credit Risk & CVA Engine: results summary", "",
        f"*Generated by `run_all.py`: valuation date {valuation_date}, {n_paths:,} Hull-White paths × {n_dates} dates, seed 42. "
        "Every number is read from `reports/tables`; see `docs/technical_note.md` for the methods.*", "",
        "## In one sentence", "",
        "A Monte Carlo counterparty-risk engine for a 10-swap interest-rate portfolio: it models future exposure under exact "
        "one-factor Hull-White rates, prices unilateral CVA from default probabilities and recovery, and measures how netting, "
        "collateral and credit and market assumptions change it.", "",
        "## Headline results", "", results_markdown(r, n_paths, n_dates, valuation_date, include_note=False, include_bullets=False), "",
        f"- The deterministic curve-discount benchmark (spec §7 formula) gives {_k(cva.loc['TOTAL', 'cva_benchmark_curve_df'])}, "
        f"{cva.loc['TOTAL', 'benchmark_vs_headline']:+.1%} versus the pathwise-discounted headline.",
        f"- CVA is integrated over all {int(cva.loc['TOTAL', 'integration_intervals'])} simulation-grid intervals; yearly buckets are presentation only.",
        f"- The worst martingale z-score, |E[D(0,t)P(t,T)] − P(0,T)| / s.e., is {mart['z_score'].abs().max():.2f}.", "",
        "## Netting and collateral (CVA)", "",
        "| Netting set | Stage | CVA | vs gross |", "|---|---|---|---|",
    ]
    out += [f"| {row.netting_set_id} | {row.stage} | {_k(row.cva)} | {_reduction(row.reduction_vs_gross)} |" for row in mit.itertuples()]
    out += ["", "Margin period of risk under a zero-threshold CSA:", "",
            "| Netting set | MPoR (days) | CVA | Share of uncollateralized |", "|---|---|---|---|"]
    out += [f"| {row.netting_set_id} | {row.mpor_days} | {_k(row.cva)} | {row.cva_share_of_uncollateralized:.1%} |"
            for row in mpor.itertuples()]
    out += ["", "## What moves portfolio CVA", "", f"Base portfolio CVA {_k(tornado['base_cva'].iloc[0])}; each input moved alone.", "",
            "| Input | Value | Portfolio CVA | Change |", "|---|---|---|---|"]
    for parameter in f["spans"].index:
        for row in tornado[tornado["parameter"] == parameter].itertuples():
            out.append(f"| {PLAIN_DRIVER_NAMES[parameter]} | {VALUE_FORMATS[parameter].format(row.value)} | {_k(row.cva)} | "
                       f"{row.change_vs_base:+.0%} |")
    conv = f["conv_total"]
    out += ["", "## Monte Carlo convergence (portfolio CVA)", "", "| Paths | CVA | Std error | 95% interval |", "|---|---|---|---|"]
    out += [f"| {row.n_paths:,} | {_k(row.cva)} | {_k(row.cva_se)} | {_k(row.ci95_low)} – {_k(row.ci95_high)} |" for row in conv.itertuples()]
    out += ["", "## Project summary", ""] + [f"- {b}" for b in resume_bullets(r, n_paths, n_dates)]
    out += ["", "## Limitations", "",
            "- Single-curve Treasury discounting and projection; no day counts, calendars or historical fixings.",
            "- One-factor Gaussian Hull-White with assumed (not calibrated) parameters: all rates move together and rates can go negative.",
            "- Assumed CDS-equivalent spreads with the credit-triangle hazard λ ≈ s/(1−R); deterministic hazards independent of rates (no wrong-way risk); unilateral CVA only.",
            "- Simplified one-way CSA: MTA added to the threshold, coupons paid during the MPoR, no initial margin or haircuts.", ""]
    return "\n".join(out)


def write_final_summary(path: Path, tables_dir: Path, n_paths: int, n_dates: int, valuation_date: str) -> None:
    path.write_text(final_summary_markdown(load_results(tables_dir), n_paths, n_dates, valuation_date))


def update_readme_results(readme: Path, tables_dir: Path, n_paths: int, n_dates: int, valuation_date: str) -> bool:
    """Replace the block between the README's results markers; returns False if the markers are missing."""
    text = readme.read_text()
    if RESULTS_START not in text or RESULTS_END not in text:
        return False
    block = results_markdown(load_results(tables_dir), n_paths, n_dates, valuation_date)
    pattern = re.compile(re.escape(RESULTS_START) + r".*?" + re.escape(RESULTS_END), re.S)
    readme.write_text(pattern.sub(lambda _: f"{RESULTS_START}\n{block}\n{RESULTS_END}", text))
    return True
